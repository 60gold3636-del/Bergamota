#!/usr/bin/env python3
"""Pre-render the Bergamota fastboot screen art (small logo + laptop/cable scene) into enxerto/fbart.h.

  python3 tools/mkfbart.py [--out <worktree>/enxerto/fbart.h] [--logo 176] [--scene 640x800] [--preview dir]

Same palette+RLE format as tools/mkbootlogo.py (index 0 = BG_BOOT), one palette per picture.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bergamota_img import BG, Canvas, crop_alpha, read_png, resize_rgba, write_png
from mkbootlogo import decode, median_cut, rle_row

HERE = os.path.dirname(os.path.abspath(__file__))


def square(img):
    w0, h0, _ = img
    s = max(w0, h0)
    big = (s, s, bytearray(s * s * 4))
    for y in range(h0):
        o = ((y + (s - h0) // 2) * s + (s - w0) // 2) * 4
        big[2][o:o + w0 * 4] = img[2][y * w0 * 4:(y + 1) * w0 * 4]
    return big


def encode(img, W, H):
    c = Canvas(W, H, BG)
    c.blit(resize_rgba(img, W, H), 0, 0)
    pixels = [tuple(c.px[i * 3:i * 3 + 3]) for i in range(W * H)]
    hist = {}
    for p in pixels:
        if p != BG:
            hist[p] = hist.get(p, 0) + 1
    pal = [BG] + median_cut(hist, 255)
    cache = {BG: 0}

    def nearest(p):
        v = cache.get(p)
        if v is None:
            v = min(range(len(pal)), key=lambda i: sum((pal[i][k] - p[k]) ** 2 for k in range(3)))
            cache[p] = v
        return v

    idx = [[nearest(pixels[y * W + x]) for x in range(W)] for y in range(H)]
    rle = bytearray()
    for row in idx:
        rle += rle_row(row)
    assert decode(rle, W, H) == idx
    return pal, rle, idx


def emit(f, name, W, H, pal, rle):
    N = name.upper()
    f.write("#define %s_W %d\n#define %s_H %d\n" % (N, W, N, H))
    f.write("static const unsigned int %s_pal[256] = {" % name)
    for i, (r, g, b) in enumerate(pal + [BG] * (256 - len(pal))):
        f.write("%s0xff%02x%02x%02x," % ("\n\t" if i % 8 == 0 else " ", r, g, b))
    f.write("\n};\nstatic const unsigned char %s_rle[%d] = {" % (name, len(rle)))
    for i, v in enumerate(rle):
        f.write("%s0x%02x," % ("\n\t" if i % 16 == 0 else "", v))
    f.write("\n};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "ios-beryllium-ios18", "enxerto", "fbart.h"))
    ap.add_argument("--logo", type=int, default=176)
    ap.add_argument("--scene", default="640x800")
    ap.add_argument("--preview")
    a = ap.parse_args()
    sw, sh = map(int, a.scene.split("x"))
    logo = square(crop_alpha(read_png(os.path.join(HERE, "assets", "bergamota-logo.png")), pad=24))
    scene = read_png(os.path.join(HERE, "assets", "bergamota-fastboot-scene.png"))
    pics = [("fbart_logo", a.logo, a.logo, logo), ("fbart_scene", sw, sh, scene)]
    with open(a.out, "w") as f:
        f.write("/* generated by tools/mkfbart.py from tools/assets/bergamota-{logo,fastboot-scene}.png: do not edit */\n")
        total = 0
        for name, W, H, img in pics:
            pal, rle, idx = encode(img, W, H)
            emit(f, name, W, H, pal, rle)
            total += len(rle)
            print("%s %dx%d RLE %d bytes" % (name, W, H, len(rle)))
            if a.preview:
                out = bytearray()
                for row in idx:
                    for v in row:
                        out += bytes(pal[v])
                write_png(os.path.join(a.preview, name + ".png"), W, H, out)
    print("total RLE %d -> %s" % (total, a.out))


if __name__ == "__main__":
    main()
